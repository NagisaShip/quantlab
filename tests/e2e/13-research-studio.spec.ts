import { expect, test } from '@playwright/test'
import path from 'node:path'
import { api, registerOrLogin, uiLogin, waitRun } from './helpers'
import { ARTIFACTS } from './run-env'

test('研究路径、结果预览、实验表单、产物与插件管理贯通', async({page,request})=>{
  const session=await registerOrLogin(request)
  const workspaceId=session.workspaceId
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  const upload=await request.post('/api/workflows/files?name=studio.csv',{headers:{'X-Workspace-Id':workspaceId,'Content-Type':'application/octet-stream'},data:'year,value\n2021,1\n2022,2\n2023,3\n2024,4\n'})
  expect(upload.ok()).toBeTruthy()
  const file=await upload.json()
  const catalog=await api(request,'/api/workflows/catalog',{workspaceId})
  const flow=catalog.body.templates.find((f:any)=>f.title==='CSV数据研究')
  flow.title='年度数据研究 · Studio 验收'
  flow.nodes[0].params.file=file.name
  const chart=catalog.body.cards.find((d:any)=>d.kind==='research.chart')
  flow.nodes.push({id:'chart',kind:chart.kind,version:chart.version,title:'年度趋势图',params:{chart_type:'line',x:'year',y:'value'},position:{x:350,y:360}})
  flow.edges.push({id:'chart-edge',source:'source',source_port:'data',target:'chart',target_port:'data'})
  const saved=await api(request,'/api/workflows',{workspaceId,method:'POST',data:{workflow:flow}})
  expect(saved.status).toBe(200)
  const wid=saved.body.id
  const started=await api(request,`/api/workflows/${wid}/run`,{workspaceId,method:'POST',data:{}})
  expect(started.status).toBe(200)
  const run=await waitRun(request,workspaceId,started.body.id)
  expect(run.state,run.error).toBe('COMPLETED')
  await uiLogin(page,session)
  await page.setViewportSize({width:1536,height:1040})
  await page.goto(`/#/workflows/${wid}`)
  await expect(page.getByRole('tab',{name:'研究路径',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(page.locator('.react-flow__node')).toHaveCount(5)
  await page.screenshot({path:path.join(ARTIFACTS,'studio-path.png'),fullPage:true})
  await page.getByRole('button',{name:/最近一次结果/}).click()
  await expect(page.getByRole('region',{name:'最近运行结果'})).toBeVisible()
  await expect(page.locator('.rs-dock .rs-image img')).toBeVisible()
  await expect.poll(()=>page.locator('.rs-dock .rs-image img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({path:path.join(ARTIFACTS,'studio-figure.png'),fullPage:true})
  await page.getByRole('combobox',{name:'查看节点结果'}).selectOption('source')
  await expect(page.locator('.rs-dock .rs-table tbody tr')).toHaveCount(4)
  // 结果 Dock 默认 compact：筛选/分页是显式「详情」里的完整阅读路径。
  await page.getByRole('button',{name:'详情'}).click()
  await expect(page.locator('.rs-dock').getByLabel('筛选当前页数据')).toBeVisible()
  await page.locator('.rs-dock').getByLabel('筛选当前页数据').fill('2023')
  await expect(page.locator('.rs-dock .rs-table tbody tr')).toHaveCount(1)
  await page.locator('.rs-dock').getByLabel('筛选当前页数据').fill('')
  await page.screenshot({path:path.join(ARTIFACTS,'studio-results.png'),fullPage:true})
  // A real parameter change marks only its downstream branch as stale.
  await page.locator('.react-flow__node').first().click()
  await page.getByRole('textbox',{name:'研究名称'}).fill('年度数据研究 · 标题修改')
  await expect(page.locator('.wf-card.stale')).toHaveCount(0)
  await page.getByRole('tab',{name:'实验与比较',exact:true}).click()
  await page.getByLabel('实验模块 1',{exact:true}).selectOption('source')
  await page.getByLabel('实验参数 1',{exact:true}).selectOption('max_rows')
  await page.getByLabel('候选值 1',{exact:true}).fill('10,20')
  await page.getByRole('button',{name:'预检并预览组合',exact:true}).click()
  await expect(page.locator('.rs-plan-preview > div')).toHaveCount(2)
  await expect(page.getByRole('button',{name:/提交 2 组实验/})).toBeEnabled()
  await page.screenshot({path:path.join(ARTIFACTS,'studio-experiments.png'),fullPage:true})
  await page.getByRole('tab',{name:'研究成果',exact:true}).click()
  await expect(page.locator('.rs-center-item').first()).toBeVisible()
  await page.getByRole('button',{name:/年度趋势图 · chart/}).click()
  await expect(page.locator('.rs-center .rs-image img')).toBeVisible()
  await page.getByLabel('研究笔记内容').fill('样本共四个年度。结论须结合完整样本检验。')
  await page.getByRole('button',{name:'引用到研究笔记',exact:true}).click()
  await page.getByRole('button',{name:'保存笔记',exact:true}).click()
  await expect(page.getByRole('region',{name:'研究笔记'})).toContainText('v1')
  await page.screenshot({path:path.join(ARTIFACTS,'studio-artifacts.png'),fullPage:true})
  await page.emulateMedia({colorScheme:'dark'})
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.screenshot({path:path.join(ARTIFACTS,'studio-dark.png'),fullPage:true})
  await page.emulateMedia({colorScheme:'light'})
  await page.goto('/#/settings/plugins')
  await expect(page.getByRole('heading',{name:'插件管理',exact:true})).toBeVisible()
  const toggle=page.getByRole('switch',{name:'因子研究 显示导航',exact:true})
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked','false')
  await page.screenshot({path:path.join(ARTIFACTS,'studio-plugins.png'),fullPage:true})
  await page.reload()
  await expect(page.getByRole('switch',{name:'因子研究 显示导航',exact:true})).toHaveAttribute('aria-checked','false')
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:path.join(ARTIFACTS,'studio-plugins-mobile.png'),fullPage:true})
  await page.goto(`/#/workflows/${wid}?run_id=${run.id}`)
  await expect(page.locator('.rs-dock')).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
  await page.screenshot({path:path.join(ARTIFACTS,'studio-mobile.png'),fullPage:true})
  expect(errors).toEqual([])
})
