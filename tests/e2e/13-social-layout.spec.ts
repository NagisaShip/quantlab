test('New conversation visibility defaults to private and is configurable in settings', async ({ page, request }) => {
  const session = await registerOrLogin(request)
  const initial = await api(request, '/api/lab/projects', { workspaceId: session.workspaceId, method: 'POST', data: { title: 'Private by default' } })
  expect(initial.status).toBe(200)
  const initialShare = await api(request, `/api/collab/shares/project/${initial.body.project.id}`, { workspaceId: session.workspaceId })
  expect(initialShare.body.share.visibility).toBe('private')
  await uiLogin(page, session)
  await page.goto('/#/settings/account')
  const choice = page.getByRole('combobox', { name: '新对话默认可见性', exact: true })
  await expect(choice).toHaveValue('private')
  await choice.selectOption('workspace')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/community/profile') && r.request().method() === 'PUT')
  await page.getByRole('button', { name: '保存资料与展示', exact: true }).click()
  expect((await saved).status()).toBe(200)
  await page.reload()
  await expect(choice).toHaveValue('workspace')
  const next = await api(request, '/api/lab/projects', { workspaceId: session.workspaceId, method: 'POST', data: { title: 'Configured shared default' } })
  expect(next.status).toBe(200)
  const share = await api(request, `/api/collab/shares/project/${next.body.project.id}`, { workspaceId: session.workspaceId })
  expect(share.body.share.visibility).toBe('workspace')
  const kept = await api(request, `/api/collab/shares/project/${initial.body.project.id}`, { workspaceId: session.workspaceId })
  expect(kept.body.share.visibility).toBe('private')
})
