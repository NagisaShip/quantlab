def apply(*routers) -> int:
    """把中文摘要挂到路由上，返回被设置的路由数。

    必须在 `app.include_router(...)` **之前** 调用：FastAPI 会把路由对象包一层
    `_IncludedRouter`，之后在 app.routes 上遍历就拿不到原始 APIRoute 了。
    """
    count = 0
    for router in routers:
        for route in getattr(router, "routes", []):
            path = getattr(route, "path", None)
            methods = getattr(route, "methods", None) or []
            if not path:
                continue
            for method in methods:
                summary = SUMMARIES.get((method, path))
                if summary:
                    route.summary = summary
                    count += 1
                    break
    return count
